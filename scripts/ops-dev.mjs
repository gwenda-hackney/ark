#!/usr/bin/env node
/**
 * Local ops: write .dev.vars, run Pages Functions on :8788, Vite menu SPA on :5174.
 *
 * Open http://127.0.0.1:5174/menu/ (API proxied to wrangler).
 * Gate/password still served by wrangler at :8788.
 *
 *   npm run dev -w @gwenda/ops
 */
import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../marketing/web/functions/_lib/env-pem.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OPS_DIR = resolve(ROOT, "ops/site");
const MENU_APP = resolve(OPS_DIR, "menu-app");
const ENV_PATH = resolve(ROOT, ".env");
const DEV_VARS_PATH = resolve(OPS_DIR, ".dev.vars");

const DEV_VAR_KEYS = [
  "OPS_PASSWORD",
  "OPS_BYPASS_KEY",
  "BASEROW_API_KEY",
  "BASEROW_OPS_DATABASE_ID",
  "BASEROW_OPS_SECTIONS_TABLE_ID",
  "BASEROW_OPS_ITEMS_TABLE_ID",
  "BASEROW_OPS_INGREDIENTS_TABLE_ID",
  "SANITY_API_TOKEN",
  "SANITY_PROJECT_ID",
  "SANITY_DATASET",
  "SITE_DEPLOY_WEBHOOK_URL",
  "SANITY_STUDIO_SITE_DEPLOY_URL",
  "DEPLOY_WEBHOOK_SECRET",
  "SANITY_STUDIO_SITE_DEPLOY_SECRET",
];

function loadRootEnv() {
  if (!existsSync(ENV_PATH)) return;
  for (const [key, value] of parseDotEnv(readFileSync(ENV_PATH, "utf8"))) {
    if (!process.env[key]) process.env[key] = value;
  }
}

function writeDevVars() {
  const lines = [
    "# Generated by npm run dev -w @gwenda/ops from repo-root .env",
    "# Do not commit.",
  ];
  for (const key of DEV_VAR_KEYS) {
    const value = process.env[key]?.trim();
    if (!value) continue;
    lines.push(`${key}=${value}`);
  }
  if (!process.env.OPS_PASSWORD?.trim()) {
    throw new Error(
      "OPS_PASSWORD missing in repo-root .env (and shell).\n" +
        "Set it with: npm run env:set -- OPS_PASSWORD '…'",
    );
  }
  writeFileSync(DEV_VARS_PATH, `${lines.join("\n")}\n`);
  console.log(`Wrote ${DEV_VARS_PATH}`);
}

loadRootEnv();
writeDevVars();

const children = [];

function run(command, args, cwd, name) {
  const child = spawn(command, args, {
    cwd,
    stdio: "inherit",
    env: process.env,
    shell: process.platform === "win32",
  });
  child.on("exit", (code, signal) => {
    for (const other of children) {
      if (other !== child && !other.killed) other.kill("SIGTERM");
    }
    process.exit(code ?? (signal ? 1 : 0));
  });
  children.push(child);
  console.log(`[ops-dev] started ${name}`);
  return child;
}

console.log(`
Ops local:
  Menu SPA (HMR):  http://localhost:5174/menu/
  Pages + gate:    http://localhost:8788/
  Password:        OPS_PASSWORD from .env
  Tip: log in at http://localhost:8788/gate/?next=/menu/ then open the SPA,
  or use the built app at http://localhost:8788/menu/ after npm run build -w @gwenda/ops
`);

run(
  "npx",
  ["wrangler", "pages", "dev", "src", "--port", "8788"],
  OPS_DIR,
  "wrangler",
);
run("npx", ["vite", "--host", "localhost"], MENU_APP, "vite");

function shutdown() {
  for (const child of children) {
    if (!child.killed) child.kill("SIGTERM");
  }
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
