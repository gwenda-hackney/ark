#!/usr/bin/env node
/**
 * Local ops: write .dev.vars, run Pages Functions on :8788, Vite ops SPA on :5174.
 *
 * Loads repo-root `.env` (marketing / shared) then `.env.ops` (ops secrets win).
 * Non-secret ops settings come from Baserow App Config at runtime.
 *
 *   npm run dev -w @gwenda/ops
 */
import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../marketing/web/functions/_lib/env-pem.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OPS_DIR = resolve(ROOT, "ops/site");
const MENU_APP = resolve(OPS_DIR, "menu-app");
const ENV_PATH = resolve(ROOT, ".env");
const OPS_ENV_PATH = resolve(ROOT, ".env.ops");
const DEV_VARS_PATH = resolve(OPS_DIR, ".dev.vars");

/** Secrets + App Config fills written into .dev.vars. Database id comes from wrangler [vars]. */
const DEV_VAR_KEYS = [
  "OPS_LOCAL_ADMIN_PW",
  "OPS_BYPASS_KEY",
  "OPS_SESSION_SECRET",
  "GOOGLE_OAUTH_CLIENT_ID",
  "GOOGLE_OAUTH_CLIENT_SECRET",
  "BASEROW_API_KEY",
  "SANITY_API_TOKEN",
  "DEPLOY_WEBHOOK_SECRET",
  "SANITY_STUDIO_SITE_DEPLOY_SECRET",
  // Optional env overrides (normally App Config):
  "SANITY_PROJECT_ID",
  "SANITY_DATASET",
  "SITE_DEPLOY_WEBHOOK_URL",
  "SANITY_STUDIO_SITE_DEPLOY_URL",
];

function loadEnvFile(path, { override = false } = {}) {
  if (!existsSync(path)) return false;
  for (const [key, value] of parseDotEnv(readFileSync(path, "utf8"))) {
    if (override || !process.env[key]) process.env[key] = value;
  }
  return true;
}

function loadRootEnv() {
  const hadShared = loadEnvFile(ENV_PATH, { override: false });
  const hadOps = loadEnvFile(OPS_ENV_PATH, { override: true });
  if (!hadShared && !hadOps) {
    console.warn("No .env or .env.ops found at repo root.");
  } else if (hadOps) {
    console.log("Loaded .env.ops (ops secrets; overrides .env).");
  }
}

function writeDevVars() {
  const lines = [
    "# Generated by npm run dev -w @gwenda/ops from .env + .env.ops",
    "# Do not commit. Plain ops config is loaded from Baserow App Config.",
  ];
  for (const key of DEV_VAR_KEYS) {
    const value = process.env[key]?.trim();
    if (!value) continue;
    lines.push(`${key}=${value}`);
  }
  lines.push("SITE_ENV=local");

  const googleId = process.env.GOOGLE_OAUTH_CLIENT_ID?.trim();
  const googleSecret = process.env.GOOGLE_OAUTH_CLIENT_SECRET?.trim();
  const session = process.env.OPS_SESSION_SECRET?.trim();
  const password =
    process.env.OPS_LOCAL_ADMIN_PW?.trim() ||
    process.env.OPS_PASSWORD?.trim();

  if (googleId && googleSecret && session) {
    // Google mode
  } else if (password) {
    // Password-only fallback
  } else {
    throw new Error(
      "Set GOOGLE_OAUTH_CLIENT_ID/SECRET + OPS_SESSION_SECRET (or OPS_LOCAL_ADMIN_PW) in .env.ops (or .env).",
    );
  }
  writeFileSync(DEV_VARS_PATH, `${lines.join("\n")}\n`);
  console.log(`Wrote ${DEV_VARS_PATH}`);
}

async function main() {
  loadRootEnv();
  // Pull plain settings (e.g. Google client id) from App Config when missing in env.
  if (process.env.BASEROW_API_KEY?.trim()) {
    try {
      const { applyOpsAppConfig } = await import(
        "../ops/site/functions/_lib/config-store.js"
      );
      const merged = await applyOpsAppConfig({
        ...process.env,
        SITE_ENV: "local",
      });
      for (const key of [
        "GOOGLE_OAUTH_CLIENT_ID",
        "SANITY_PROJECT_ID",
        "SANITY_DATASET",
        "SITE_DEPLOY_WEBHOOK_URL",
        "SANITY_STUDIO_SITE_DEPLOY_URL",
      ]) {
        if (!process.env[key]?.trim() && merged[key]) {
          process.env[key] = merged[key];
        }
      }
      console.log("Merged ops App Config into local env (non-secrets).");
    } catch (error) {
      console.warn(
        `App Config not loaded (${error instanceof Error ? error.message : error}). Using env only.`,
      );
    }
  }
  writeDevVars();

  const children = [];

  function run(command, args, cwd, name) {
    const child = spawn(command, args, {
      cwd,
      stdio: "inherit",
      env: process.env,
      shell: process.platform === "win32",
    });
    child.on("exit", (code, signal) => {
      for (const other of children) {
        if (other !== child && !other.killed) other.kill("SIGTERM");
      }
      process.exit(code ?? (signal ? 1 : 0));
    });
    children.push(child);
    console.log(`[ops-dev] started ${name}`);
    return child;
  }

  const googleReady = Boolean(
    process.env.GOOGLE_OAUTH_CLIENT_ID?.trim() &&
      process.env.GOOGLE_OAUTH_CLIENT_SECRET?.trim() &&
      process.env.OPS_SESSION_SECRET?.trim(),
  );
  console.log(`
Ops local:
  SPA (HMR):       http://localhost:5174/
  Pages + auth:    http://localhost:8788/
  Auth:            ${
    googleReady
      ? "Google OAuth + Baserow Users (same as production)"
      : "OPS_LOCAL_ADMIN_PW gate"
  }
`);

  run(
    "npx",
    ["wrangler", "pages", "dev", "src", "--ip", "0.0.0.0", "--port", "8788"],
    OPS_DIR,
    "wrangler",
  );
  run("npx", ["vite", "--host", "0.0.0.0"], MENU_APP, "vite");

  function shutdown() {
    for (const child of children) {
      if (!child.killed) child.kill("SIGTERM");
    }
  }
  process.on("SIGINT", shutdown);
  process.on("SIGTERM", shutdown);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
