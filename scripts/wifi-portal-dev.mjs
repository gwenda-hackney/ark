#!/usr/bin/env node
/**
 * Local Wi‑Fi captive portal: sync secrets from repo-root .env into
 * utils/wifi-captive-portal/.dev.vars, then run `wrangler dev`.
 *
 *   npm run wifi-portal
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../web/functions/_lib/env-pem.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const WORKER_DIR = resolve(ROOT, "utils/wifi-captive-portal");
const ENV_PATH = resolve(ROOT, ".env");
const DEV_VARS_PATH = resolve(WORKER_DIR, ".dev.vars");

const SECRET_KEYS = ["BASEROW_API_KEY", "UNIFI_SITE_MANAGER_API_KEY"];

function loadRootEnv() {
  if (!existsSync(ENV_PATH)) return;
  for (const [key, value] of parseDotEnv(readFileSync(ENV_PATH, "utf8"))) {
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function writeDevVars() {
  const lines = [
    "# Generated by npm run wifi-portal from repo-root .env",
    "# Do not commit.",
  ];
  const missing = [];

  for (const key of SECRET_KEYS) {
    const value = process.env[key]?.trim();
    if (!value) {
      missing.push(key);
      continue;
    }
    lines.push(`${key}=${value}`);
  }

  if (missing.length) {
    throw new Error(
      `Missing in .env: ${missing.join(", ")}\n` +
        "Need BASEROW_API_KEY and UNIFI_SITE_MANAGER_API_KEY for local portal.",
    );
  }

  writeFileSync(DEV_VARS_PATH, `${lines.join("\n")}\n`);
  console.log(`Wrote ${DEV_VARS_PATH}`);
}

loadRootEnv();
writeDevVars();

const extra = process.argv.slice(2);
const result = spawnSync(
  "npx",
  ["wrangler", "dev", "--local", ...extra],
  {
    cwd: WORKER_DIR,
    stdio: "inherit",
    env: {
      ...process.env,
      CLOUDFLARE_API_TOKEN:
        process.env.CLOUDFLARE_API_TOKEN?.trim() || undefined,
    },
  },
);

process.exit(result.status ?? 1);
