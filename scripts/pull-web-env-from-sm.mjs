#!/usr/bin/env node
/**
 * Pull marketing web secrets from Bitwarden Secrets Manager → repo-root `.env.web`.
 *
 * Bootstrap (shared `.env` only):
 *   ARK_LOCAL_BW_TOKEN   machine-account access token (ark-local)
 *
 * SM stores the marketing Baserow token as BASEROW_API_KEY_MARKETING
 * (written locally as BASEROW_API_KEY). Ops Free-workspace key is separate.
 *
 * CI uses BWS_ACCESS_TOKEN (ark-ci), then:
 *   npm run env:web:pull -- --github-env   # before sync-pages-secrets in web-secrets.yml
 *
 *   npm run env:web:pull
 *   npm run env:web:pull -- --dry-run
 *   npm run env:web:pull -- --env-only
 *   npm run env:web:pull -- --github-env
 */
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../marketing/web/functions/_lib/env-pem.js";
import {
  WEB_ENV_SECRET_KEYS,
  listSmSecrets,
  pickWebSecrets,
  resolveSmAccessToken,
  resolveWebProjectId,
} from "./lib/bitwarden-sm.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = resolve(root, ".env");
const WEB_ENV_PATH = resolve(root, ".env.web");

function loadDotEnv(path) {
  if (!existsSync(path)) return new Map();
  return new Map(parseDotEnv(readFileSync(path, "utf8")));
}

function parseArgs(argv) {
  const out = { dryRun: false, envOnly: false, githubEnv: false };
  for (const arg of argv) {
    if (arg === "--dry-run") out.dryRun = true;
    else if (arg === "--env-only") out.envOnly = true;
    else if (arg === "--github-env") out.githubEnv = true;
    else if (arg === "--help" || arg === "-h") out.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return out;
}

function formatWebEnv(values) {
  const lines = [
    "# Generated by npm run env:web:pull from Bitwarden Secrets Manager.",
    "# Do not commit. Bootstrap token lives in shared .env (ARK_LOCAL_BW_TOKEN).",
    "# Subscribe / RSVP table ids are resolved by name (docs/config.md).",
    "# BASEROW_API_KEY here is BASEROW_API_KEY_MARKETING from SM (not ops Free key).",
    "",
  ];
  for (const key of WEB_ENV_SECRET_KEYS) {
    let value = values.get(key) ?? "";
    // Gmail app passwords are often stored with spaces; strip for SMTP and so
    // `source .env.web` does not truncate at the first space.
    if (key === "SMTP_PASSWORD") {
      value = String(value).replace(/\s+/g, "");
    }
    lines.push(`${key}=${shellQuoteEnvValue(value)}`);
  }
  return `${lines.join("\n")}\n`;
}

/** Quote values so `source .env.web` keeps spaces and special chars intact. */
function shellQuoteEnvValue(value) {
  const raw = String(value ?? "");
  if (!raw) return "";
  if (/^[A-Za-z0-9_./:@+-]+$/.test(raw)) return raw;
  return `"${raw.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/`/g, "\\`")}"`;
}

/** GitHub Actions multiline env file syntax. */
function appendGithubEnv(fromWeb) {
  const path = process.env.GITHUB_ENV?.trim();
  if (!path) {
    throw new Error("--github-env requires GITHUB_ENV (GitHub Actions only).");
  }
  let n = 0;
  for (const key of WEB_ENV_SECRET_KEYS) {
    const value = fromWeb.get(key);
    if (value == null || !String(value).trim()) continue;
    appendFileSync(path, `${key}<<BW_EOF\n${value}\nBW_EOF\n`);
    n += 1;
  }
  return n;
}

function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
  if (opts.help) {
    console.log(`Usage: node scripts/pull-web-env-from-sm.mjs [--dry-run] [--env-only] [--github-env]

  --dry-run      List keys that would sync (no write, no values)
  --env-only     Print KEY=value lines to stdout; do not write .env.web
  --github-env   Append filled secrets to $GITHUB_ENV
`);
    return;
  }

  const shared = loadDotEnv(ENV_PATH);
  for (const [key, value] of shared) {
    if (!process.env[key]) process.env[key] = value;
  }

  const token = resolveSmAccessToken();
  if (!token) {
    console.error(
      "Set ARK_LOCAL_BW_TOKEN in repo-root .env (or BWS_ACCESS_TOKEN / ARK_CI_BW_TOKEN).",
    );
    process.exit(1);
  }

  const all = listSmSecrets({
    accessToken: token,
    projectId: resolveWebProjectId(),
  });
  const fromSm = pickWebSecrets(all);
  const existing = loadDotEnv(WEB_ENV_PATH);
  const web = new Map();
  for (const key of WEB_ENV_SECRET_KEYS) {
    if (fromSm.has(key) && String(fromSm.get(key) ?? "").trim()) {
      web.set(key, fromSm.get(key));
    } else if (existing.has(key)) {
      web.set(key, existing.get(key) ?? "");
    } else {
      web.set(key, fromSm.get(key) ?? "");
    }
  }
  const missing = WEB_ENV_SECRET_KEYS.filter((key) => {
    if (key === "BASEROW_API_KEY") {
      return !String(all.get("BASEROW_API_KEY_MARKETING") ?? "").trim();
    }
    return !fromSm.has(key) || !String(fromSm.get(key) ?? "").trim();
  });
  const fromSmFilled = WEB_ENV_SECRET_KEYS.filter(
    (key) => fromSm.has(key) && String(fromSm.get(key) ?? "").trim(),
  );

  if (opts.dryRun) {
    console.log(`Would write ${WEB_ENV_PATH}`);
    console.log(`SM project: Ark/Web (${resolveWebProjectId()})`);
    console.log(`From SM: ${fromSmFilled.join(", ") || "(none)"}`);
    if (missing.length) {
      console.log(`Missing in SM (keep local if present): ${missing.join(", ")}`);
    }
    const ignored = [...all.keys()].filter((k) => {
      if (k === "BASEROW_API_KEY_MARKETING") return false;
      return !WEB_ENV_SECRET_KEYS.includes(k);
    });
    if (ignored.length) {
      console.log(`SM keys not written to .env.web: ${ignored.join(", ")}`);
    }
    return;
  }

  if (opts.githubEnv) {
    const smKeyNames = [...all.keys()].sort();
    console.log(
      `SM project Ark/Web (${resolveWebProjectId()}): ${smKeyNames.length} keys (${smKeyNames.join(", ") || "none"})`,
    );
    console.log(`Filled web secrets from SM: ${fromSmFilled.join(", ") || "(none)"}`);
    if (missing.length) {
      console.log(`Missing in SM: ${missing.join(", ")}`);
    }
    const n = appendGithubEnv(web);
    console.log(`Appended ${n} secrets to GITHUB_ENV (from SM).`);
    if (n === 0) {
      throw new Error(
        "No web secrets were loaded from Secrets Manager into GITHUB_ENV. Check BWS_ACCESS_TOKEN access to the Ark/Web project.",
      );
    }
    return;
  }

  if (opts.envOnly) {
    for (const key of WEB_ENV_SECRET_KEYS) {
      const value = web.get(key);
      if (value == null || !String(value).trim()) continue;
      process.stdout.write(`${key}=${value}\n`);
    }
    return;
  }

  writeFileSync(WEB_ENV_PATH, formatWebEnv(web));
  console.log(`Wrote ${WEB_ENV_PATH}`);
  console.log(`Synced from SM: ${fromSmFilled.join(", ") || "(none)"}`);
  const keptLocal = WEB_ENV_SECRET_KEYS.filter(
    (key) =>
      !String(fromSm.get(key) ?? "").trim() && String(web.get(key) ?? "").trim(),
  );
  if (keptLocal.length) {
    console.log(`Kept local (not in SM): ${keptLocal.join(", ")}`);
  }
  if (missing.length) {
    console.log(
      `Not in SM yet: ${missing.join(", ")}. Add via npm run env:web:push or Secrets Manager.`,
    );
  }
}

main();
