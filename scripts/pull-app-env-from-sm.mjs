#!/usr/bin/env node
/**
 * Pull secrets from Bitwarden Secrets Manager for one env.
 *
 * Every SM secret is `NAME` (shared) or `NAME__LOCAL|__STAGING|__PRODUCTION`
 * (env override). The override wins. See scripts/lib/bitwarden-sm.mjs.
 *
 *   npm run env:secrets:pull                      # .env.secrets (local, SM names)
 *   npm run env:secrets:pull -- --profile staging --dry-run
 *   npm run env:ops:pull -- --github-env          # CI, ops runtime names, production
 *   npm run env:web:pull -- --github-env          # CI, web runtime names, production
 *
 * The local file holds every app's secrets once, under SM names. Wrappers
 * (with-env, with-ops-env, ops-dev) map them to each app's runtime names.
 * `--github-env` exports one app's runtime names plus the Ark keys.
 *
 * Bootstrap: ARK_LOCAL_BW_TOKEN in repo-root `.env` (local), BWS_ACCESS_TOKEN (CI).
 */
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../marketing/web/functions/_lib/env-pem.js";
import {
  APP_SECRETS,
  LOCAL_SECRETS_FILE,
  appSecrets,
  listAllSmSecrets,
  localSecretNames,
  normalizeSecretEnv,
  pickAppSecrets,
  resolveSecretsForEnv,
  resolveSmAccessToken,
  smNameFor,
} from "./lib/bitwarden-sm.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Default env when --profile is omitted. CI jobs rely on these. */
const GITHUB_DEFAULT_ENV = { ark: "production", ops: "production", web: "production" };
const LEGACY_FILES = [".env.ark", ".env.ops", ".env.web"];

function loadDotEnv(path) {
  if (!existsSync(path)) return new Map();
  return new Map(parseDotEnv(readFileSync(path, "utf8")));
}

function parseArgs(argv) {
  const out = { app: "", dryRun: false, envOnly: false, githubEnv: false, env: "" };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--dry-run") out.dryRun = true;
    else if (arg === "--env-only") out.envOnly = true;
    else if (arg === "--github-env") out.githubEnv = true;
    else if (arg === "--profile" || arg === "--env") {
      out.env = normalizeSecretEnv(argv[i + 1]);
      i += 1;
    } else if (arg === "--help" || arg === "-h") out.help = true;
    else if (!arg.startsWith("-") && !out.app) out.app = arg;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!out.help) {
    if (out.app) appSecrets(out.app);
    if ((out.githubEnv || out.envOnly) && !out.app) {
      throw new Error("--github-env / --env-only need an app (ark, ops or web).");
    }
    if (!out.env) out.env = out.githubEnv ? GITHUB_DEFAULT_ENV[out.app] : "local";
  }
  return out;
}

function quoteEnvValue(value) {
  const raw = String(value ?? "");
  if (/^[A-Za-z0-9_./:@+=,-]*$/.test(raw)) return raw;
  if (!raw.includes("'")) return `'${raw}'`;
  return `"${raw.replace(/"/g, '\\"')}"`;
}

function formatSecretsFile(env, resolved) {
  const lines = [
    `# Generated by npm run env:secrets:pull (env=${env}) from Bitwarden Secrets Manager.`,
    "# Do not commit or hand-edit. Change the secret in SM and pull again.",
    "# Keys are SM names. scripts/lib/load-env.mjs maps them to each app's runtime names.",
    "",
  ];
  const missing = [];
  for (const name of localSecretNames()) {
    const value = resolved.get(name);
    if (value === undefined || value === "") {
      missing.push(name);
      lines.push(`# ${name}= (missing in SM: ${name} or ${name}__${env.toUpperCase()})`);
      continue;
    }
    lines.push(`${name}=${quoteEnvValue(value)}`);
  }
  return { content: `${lines.join("\n")}\n`, missing };
}

function appendGithubEnv(values) {
  const path = process.env.GITHUB_ENV?.trim();
  if (!path) throw new Error("--github-env requires GITHUB_ENV (GitHub Actions only).");
  for (const [key, value] of values) {
    process.stdout.write(`::add-mask::${value}\n`);
    appendFileSync(path, `${key}<<BW_EOF\n${value}\nBW_EOF\n`);
  }
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(`Usage: node scripts/pull-app-env-from-sm.mjs <${Object.keys(APP_SECRETS).join("|")}> [options]

  No app: write ${LOCAL_SECRETS_FILE} (all secrets, SM names). With an app and
  no --github-env / --env-only, the app is ignored and the same file is written.

  --profile|--env local|staging|production
                 local by default; with --github-env: production
  --dry-run      List resolved and missing keys (no values, no write)
  --env-only     Print KEY=value lines; do not write files
  --github-env   Append resolved secrets (plus Ark keys) to $GITHUB_ENV
`);
    return;
  }

  for (const [key, value] of loadDotEnv(resolve(root, ".env"))) {
    if (!process.env[key]) process.env[key] = value;
  }
  const accessToken = resolveSmAccessToken();
  if (!accessToken) {
    console.error("Set ARK_LOCAL_BW_TOKEN in repo-root .env (or BWS_ACCESS_TOKEN in CI).");
    process.exit(1);
  }

  const resolved = resolveSecretsForEnv(listAllSmSecrets({ accessToken }), opts.env);

  if (opts.githubEnv || opts.envOnly) {
    const { values, missing } = pickAppSecrets(opts.app, resolved);
    if (missing.length) {
      console.log(`Missing in SM: ${missing.map((key) => smNameFor(opts.app, key)).join(", ")}`);
    }
    if (opts.envOnly) {
      for (const [key, value] of values) process.stdout.write(`${key}=${value}\n`);
      return;
    }
    const ark = opts.app === "ark" ? null : pickAppSecrets("ark", resolved);
    const all = new Map([...(ark?.values ?? []), ...values]);
    if (!all.size) throw new Error("No secrets resolved from Secrets Manager. Check BWS_ACCESS_TOKEN.");
    appendGithubEnv(all);
    console.log(`App ${opts.app}, env ${opts.env}: appended ${all.size} secrets to GITHUB_ENV.`);
    return;
  }

  const { content, missing } = formatSecretsFile(opts.env, resolved);
  const count = localSecretNames().length - missing.length;
  console.log(`Env ${opts.env}: ${count} secrets resolved.`);
  if (missing.length) console.log(`Missing in SM: ${missing.join(", ")}`);
  if (opts.dryRun) return;

  writeFileSync(resolve(root, LOCAL_SECRETS_FILE), content, { mode: 0o600 });
  console.log(`Wrote ${LOCAL_SECRETS_FILE}`);
  const legacy = LEGACY_FILES.filter((name) => existsSync(resolve(root, name)));
  if (legacy.length) {
    console.log(`Legacy files no longer read: ${legacy.join(", ")}. Delete them.`);
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
