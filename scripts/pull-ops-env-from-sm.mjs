#!/usr/bin/env node
/**
 * Pull ops secrets from Bitwarden Secrets Manager → repo-root `.env.ops`.
 *
 * Bootstrap (shared `.env` only):
 *   ARK_LOCAL_BW_TOKEN   machine-account access token (ark-local)
 *
 * CI uses ARK_CI_BW_TOKEN or BWS_ACCESS_TOKEN, then either:
 *   npm run env:ops:pull -- --env-only   # print KEY=value for Actions
 *   or feed setup:ops after exporting secrets into the job env
 *
 *   npm run env:ops:pull
 *   npm run env:ops:pull -- --dry-run
 *   npm run env:ops:pull -- --env-only
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDotEnv } from "../marketing/web/functions/_lib/env-pem.js";
import {
  OPS_ENV_SECRET_KEYS,
  listSmSecrets,
  pickOpsSecrets,
  resolveSmAccessToken,
} from "./lib/bitwarden-sm.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = resolve(root, ".env");
const OPS_ENV_PATH = resolve(root, ".env.ops");

function loadDotEnv(path) {
  if (!existsSync(path)) return new Map();
  return new Map(parseDotEnv(readFileSync(path, "utf8")));
}

function parseArgs(argv) {
  const out = { dryRun: false, envOnly: false };
  for (const arg of argv) {
    if (arg === "--dry-run") out.dryRun = true;
    else if (arg === "--env-only") out.envOnly = true;
    else if (arg === "--help" || arg === "-h") out.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return out;
}

function formatOpsEnv(values) {
  const lines = [
    "# Generated by npm run env:ops:pull from Bitwarden Secrets Manager.",
    "# Do not commit. Bootstrap token lives in shared .env (ARK_LOCAL_BW_TOKEN).",
    "# Plain ops settings → Baserow App Config (docs/config.md).",
    "",
  ];
  for (const key of OPS_ENV_SECRET_KEYS) {
    lines.push(`${key}=${values.get(key) ?? ""}`);
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
  if (opts.help) {
    console.log(`Usage: node scripts/pull-ops-env-from-sm.mjs [--dry-run] [--env-only]

  --dry-run    List keys that would sync (no write, no values)
  --env-only   Print KEY=value lines to stdout (for CI); do not write .env.ops
`);
    return;
  }

  // Shared .env first so ARK_LOCAL_BW_TOKEN is available.
  const shared = loadDotEnv(ENV_PATH);
  for (const [key, value] of shared) {
    if (!process.env[key]) process.env[key] = value;
  }

  const token = resolveSmAccessToken();
  if (!token) {
    console.error(
      "Set ARK_LOCAL_BW_TOKEN in repo-root .env (or BWS_ACCESS_TOKEN / ARK_CI_BW_TOKEN).",
    );
    process.exit(1);
  }

  const all = listSmSecrets({ accessToken: token });
  const fromSm = pickOpsSecrets(all);
  const existing = loadDotEnv(OPS_ENV_PATH);
  const ops = new Map();
  for (const key of OPS_ENV_SECRET_KEYS) {
    if (fromSm.has(key) && String(fromSm.get(key) ?? "").trim()) {
      ops.set(key, fromSm.get(key));
    } else if (existing.has(key)) {
      // Keep local-only values (e.g. OPS_LOCAL_ADMIN_PW) until they exist in SM.
      ops.set(key, existing.get(key) ?? "");
    } else {
      ops.set(key, fromSm.get(key) ?? "");
    }
  }
  const missing = OPS_ENV_SECRET_KEYS.filter((key) => !fromSm.has(key));
  const filled = OPS_ENV_SECRET_KEYS.filter((key) => (ops.get(key) || "").trim());
  const fromSmFilled = OPS_ENV_SECRET_KEYS.filter(
    (key) => fromSm.has(key) && String(fromSm.get(key) ?? "").trim(),
  );

  if (opts.dryRun) {
    console.log(`Would write ${OPS_ENV_PATH}`);
    console.log(`From SM: ${fromSmFilled.join(", ") || "(none)"}`);
    if (missing.length) {
      console.log(`Missing in SM (keep local if present): ${missing.join(", ")}`);
    }
    const ignored = [...all.keys()].filter((k) => !OPS_ENV_SECRET_KEYS.includes(k));
    if (ignored.length) {
      console.log(`SM keys not written to .env.ops: ${ignored.join(", ")}`);
    }
    return;
  }

  if (opts.envOnly) {
    for (const key of OPS_ENV_SECRET_KEYS) {
      const value = ops.get(key);
      if (value == null || !String(value).trim()) continue;
      process.stdout.write(`${key}=${value}\n`);
    }
    return;
  }

  writeFileSync(OPS_ENV_PATH, formatOpsEnv(ops));
  console.log(`Wrote ${OPS_ENV_PATH}`);
  console.log(`Synced from SM: ${fromSmFilled.join(", ") || "(none)"}`);
  const keptLocal = OPS_ENV_SECRET_KEYS.filter(
    (key) =>
      !String(fromSm.get(key) ?? "").trim() && String(ops.get(key) ?? "").trim(),
  );
  if (keptLocal.length) {
    console.log(`Kept local (not in SM): ${keptLocal.join(", ")}`);
  }
  if (missing.length) {
    console.log(
      `Not in SM yet: ${missing.join(", ")}. Add them in Secrets Manager when ready.`,
    );
  }
}
main();
